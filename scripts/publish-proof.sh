#!/usr/bin/env bash
# Publishes Playwright proof recordings for a PR.
#   - converts each test's video.webm to an inline GIF + MP4, copies trace.zip
#   - commits them to the orphan branch `pr-proof` under pr-<N>/<short-sha>/
#   - creates/updates one sticky PR comment that embeds the GIFs, pinned to the proof commit
# Required env: REPO, PR_NUMBER, HEAD_SHA, RUN_URL, GH_TOKEN. Arg 1: Playwright JSON report.
set -euo pipefail

REPORT="$1"
PROOF_BRANCH=pr-proof
MARKER='<!-- agent-proof -->'
SHORT_SHA="${HEAD_SHA:0:7}"
DEST="pr-${PR_NUMBER}/${SHORT_SHA}"
WORKTREE="$(mktemp -d)"

if [ ! -s "$REPORT" ]; then
  echo "No Playwright JSON report at $REPORT - nothing to publish" >&2
  exit 1
fi

# One TSV row per test: file, title, status, video path, trace path (last attempt).
ROWS=$(jq -r '
  [.. | objects | select(has("specs")) | .specs[]] | .[] | . as $spec
  | .tests[] | .results[-1] as $r
  | [ $spec.file, $spec.title, ($r.status // "unknown"),
      ([$r.attachments[]? | select(.name == "video") | .path][0] // ""),
      ([$r.attachments[]? | select(.name == "trace") | .path][0] // "") ]
  | @tsv' "$REPORT")

# Check out (or create) the orphan proof branch in a separate worktree.
git config --global user.name "github-actions[bot]"
git config --global user.email "41898282+github-actions[bot]@users.noreply.github.com"
trap 'git worktree remove --force "$WORKTREE" >/dev/null 2>&1 || true' EXIT
if git ls-remote --exit-code --heads origin "$PROOF_BRANCH" >/dev/null; then
  git fetch -q origin "$PROOF_BRANCH"
  git worktree add -q --detach "$WORKTREE" "origin/$PROOF_BRANCH"
else
  git worktree add -q --detach "$WORKTREE"
  git -C "$WORKTREE" checkout -q --orphan "$PROOF_BRANCH"
  git -C "$WORKTREE" rm -rq --cached . && find "$WORKTREE" -mindepth 1 -maxdepth 1 ! -name .git -exec rm -rf {} +
  printf '# PR proof recordings\n\nGenerated by `agent-proof.yml`. Never merged into main.\n' > "$WORKTREE/README.md"
fi
mkdir -p "$WORKTREE/$DEST"

SECTIONS=""
INDEX=0
PASSED=0
TOTAL=0
while IFS=$'\t' read -r FILE TITLE STATUS VIDEO TRACE; do
  [ -z "$FILE" ] && continue
  INDEX=$((INDEX + 1)); TOTAL=$((TOTAL + 1))
  NAME=$(printf '%02d' "$INDEX")
  ICON="❌"; [ "$STATUS" = "passed" ] && { ICON="✅"; PASSED=$((PASSED + 1)); }
  SECTIONS+=$'\n'"### ${INDEX}. ${TITLE} ${ICON}"$'\n'"\`${FILE}\` — status: \`${STATUS}\`"$'\n\n'

  if [ -n "$VIDEO" ] && [ -f "$VIDEO" ]; then
    ffmpeg -loglevel error -y -i "$VIDEO" \
      -vf "fps=10,scale=960:-1:flags=lanczos,split[a][b];[a]palettegen=max_colors=128[p];[b][p]paletteuse=dither=bayer" \
      "$WORKTREE/$DEST/$NAME.gif"
    ffmpeg -loglevel error -y -i "$VIDEO" -c:v libx264 -pix_fmt yuv420p -movflags +faststart -an \
      "$WORKTREE/$DEST/$NAME.mp4"
    SECTIONS+="__GIF_${NAME}__"$'\n\n'"[MP4](__BLOB__/$NAME.mp4)"
  else
    SECTIONS+="_(no video recorded)_"
  fi
  if [ -n "$TRACE" ] && [ -f "$TRACE" ]; then
    cp "$TRACE" "$WORKTREE/$DEST/$NAME.trace.zip"
    SECTIONS+=" · [Open trace in Trace Viewer](https://trace.playwright.dev/?trace=__RAW__/$NAME.trace.zip)"
  fi
  SECTIONS+=$'\n'
done <<< "$ROWS"

# Commit and push, retrying on concurrent pushes from other PRs.
git -C "$WORKTREE" add -A
git -C "$WORKTREE" commit -q -m "proof: PR #${PR_NUMBER} @ ${SHORT_SHA}" || true
for attempt in 1 2 3; do
  if git -C "$WORKTREE" push -q origin "HEAD:$PROOF_BRANCH"; then break; fi
  [ "$attempt" = 3 ] && { echo "Failed to push $PROOF_BRANCH" >&2; exit 1; }
  git -C "$WORKTREE" pull -q --rebase origin "$PROOF_BRANCH"
done
PROOF_SHA=$(git -C "$WORKTREE" rev-parse HEAD)

# Links are pinned to the proof commit so they keep working forever.
RAW="https://raw.githubusercontent.com/${REPO}/${PROOF_SHA}/${DEST}"
BLOB="https://github.com/${REPO}/blob/${PROOF_SHA}/${DEST}"
IMG="https://github.com/${REPO}/raw/${PROOF_SHA}/${DEST}"
SECTIONS="${SECTIONS//__RAW__/$RAW}"
SECTIONS="${SECTIONS//__BLOB__/$BLOB}"
for gif in "$WORKTREE/$DEST"/*.gif; do
  [ -e "$gif" ] || continue
  N=$(basename "$gif" .gif)
  SECTIONS="${SECTIONS//__GIF_${N}__/![test ${N}](${IMG}/${N}.gif)}"
done

BODY="${MARKER}
## 🎥 Verification proof — ${PASSED}/${TOTAL} passed

Commit \`${SHORT_SHA}\` · chromium · \`PROOF=1\` (video + trace, slowMo 800ms) · [workflow run](${RUN_URL})
${SECTIONS}
<sub>Recordings live on the \`${PROOF_BRANCH}\` branch (never merged into main). This comment is updated on every push.</sub>"

COMMENT_ID=$(gh api "repos/${REPO}/issues/${PR_NUMBER}/comments" --paginate \
  -q ".[] | select(.body | startswith(\"${MARKER}\")) | .id" | head -n1)
if [ -n "$COMMENT_ID" ]; then
  gh api -X PATCH "repos/${REPO}/issues/comments/${COMMENT_ID}" -f body="$BODY" >/dev/null
else
  gh api -X POST "repos/${REPO}/issues/${PR_NUMBER}/comments" -f body="$BODY" >/dev/null
fi
echo "Proof published: ${PASSED}/${TOTAL} passed -> ${BLOB}"
